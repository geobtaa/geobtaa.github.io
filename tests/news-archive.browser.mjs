import assert from 'node:assert/strict';
import test from 'node:test';
import { writeFile } from 'node:fs/promises';
import { chrome, withEditorBrowser } from '../editor/browserHarness.mjs';

const options = { skip: chrome || process.env.CI ? false : 'Chrome/Chromium required', timeout: 90_000 };

test('archive searches all posts, loads batches, restores article returns, and works on mobile', options, async () => {
  await withEditorBrowser('', async ({ evaluate, waitFor, send, arrow }) => {
    await waitFor('!!document.body');
    const origin = await evaluate('location.origin');
    const visit = async path => {
      const previous = await evaluate('performance.timeOrigin');
      await send('Page.navigate', { url: origin + path });
      await waitFor(`performance.timeOrigin !== ${previous} && !!document.querySelector('[data-blog-archive][data-ready]')`);
    };
    const visible = () => evaluate('[...document.querySelectorAll("[data-blog-card]:not([hidden])")].map(card => card.getAttribute("href"))');
    const input = async (selector, value) => {
      await evaluate(`(() => { const input = document.querySelector(${JSON.stringify(selector)}); input.value = ${JSON.stringify(value)}; input.dispatchEvent(new Event(input.type === 'search' ? 'input' : 'change', {bubbles:true})); })()`);
    };
    await visit('/blog/');
    assert.equal((await visible()).length, 12);
    assert.equal(await evaluate('document.querySelector("[data-archive-pagination]").hidden'), true);
    await evaluate('document.querySelector("[data-archive-more]").click()');
    assert.equal((await visible()).length, 24);
    assert.equal(await evaluate('new URLSearchParams(location.search).get("shown")'), '24');
    assert.equal(await evaluate('document.activeElement === document.querySelectorAll("[data-blog-card]:not([hidden])")[12]'), true);
    const target = await evaluate('document.querySelectorAll("[data-blog-card]")[30].dataset.search.split(" ").slice(0,3).join(" ")');
    await input('#archive-search', target);
    assert.ok((await visible()).length > 0);
    assert.equal(await evaluate('document.querySelectorAll("[data-blog-card]")[30].hidden'), false, 'search includes posts outside the initial batch');
    await input('#archive-search', 'no-results-expected-xyz');
    assert.equal((await visible()).length, 0);
    assert.equal(await evaluate('document.querySelector("[data-archive-empty]").hidden'), false);
    await evaluate('document.querySelector("[type=reset]").click()');
    assert.equal((await visible()).length, 12);
    await evaluate('document.querySelector("[name=type][value=update]").click()');
    await input('#archive-year', '2025');
    assert.equal((await visible()).length, 12);
    assert.equal(await evaluate('[...document.querySelectorAll("[data-blog-card]:not([hidden])")].every(c=>c.dataset.category==="update" && c.dataset.year==="2025")'), true);
    assert.equal(await evaluate('document.querySelector("[data-archive-more]").hidden'), true);
    await evaluate('document.querySelector("[type=reset]").click()');
    await evaluate('document.querySelector("[data-archive-more]").click()');
    const expected = await visible();
    await evaluate('document.querySelectorAll("[data-blog-card]:not([hidden])")[18].scrollIntoView()');
    const scroll = await evaluate('scrollY');
    const href = expected[18];
    await evaluate('document.querySelectorAll("[data-blog-card]:not([hidden])")[18].click()');
    await waitFor(`location.pathname === ${JSON.stringify(href)} && !!document.querySelector('[data-news-sidebar]')`);
    assert.equal(await evaluate('document.querySelectorAll("[data-news-sidebar] .recent-updates a").length'), 5);
    await evaluate('history.back()');
    await waitFor('location.pathname === "/blog/" && !!document.querySelector("[data-ready]")');
    await waitFor(`Math.abs(scrollY - ${scroll}) < 5`);
    assert.deepEqual(await visible(), expected);
    const previous = await evaluate('performance.timeOrigin');
    await send('Page.reload');
    await waitFor(`performance.timeOrigin !== ${previous} && !!document.querySelector('[data-blog-archive][data-ready]')`);
    assert.deepEqual(await visible(), expected);
    await visit('/blog/?type=post&q=maps');
    assert.equal(await evaluate('document.querySelector("#archive-search").value'), 'maps');
    assert.equal(await evaluate('document.querySelector("[name=type]:checked").value'), 'post');
    await input('#archive-year', '2026');
    assert.equal(await evaluate('new URLSearchParams(location.search).get("q")'), 'maps');
    assert.equal(await evaluate('[...document.querySelectorAll("[data-blog-card]:not([hidden])")].every(c=>c.dataset.year==="2026" && c.dataset.category==="post")'), true);
    await visit('/blog/page/3/');
    assert.equal((await visible()).length, 36);
    await send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
    await visit('/blog/');
    const desktop = await send('Page.captureScreenshot', { format: 'png' });
    await writeFile('/tmp/geobtaa-news-desktop.png', Buffer.from(desktop.data, 'base64'));
    await send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
    await visit('/blog/');
    assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true, 'mobile archive has no horizontal overflow');
    await evaluate('document.querySelector("#archive-search").focus()');
    await send('Input.insertText', { text: 'maps' });
    await arrow('Tab', 9);
    assert.equal(await evaluate('document.activeElement.name'), 'type');
    await send('Accessibility.enable');
    const { nodes } = await send('Accessibility.getFullAXTree');
    assert.ok(nodes.some(node => !node.ignored && node.role?.value === 'searchbox' && node.name?.value === 'Search News & Stories'));
    await evaluate('document.querySelector("[type=reset]").click(); window.scrollTo(0,0)');
    const screenshot = await send('Page.captureScreenshot', { format: 'png' });
    await writeFile('/tmp/geobtaa-news-mobile.png', Buffer.from(screenshot.data, 'base64'));
    await send('Emulation.setScriptExecutionDisabled', { value: true });
    await send('Page.navigate', { url: origin + '/blog/page/2/' });
    await waitFor(`location.pathname === '/blog/page/2/' && !!document.querySelector('[data-blog-archive]')`);
    assert.equal((await visible()).length, 12);
    assert.equal(await evaluate('document.querySelector("[data-archive-pagination]").hidden'), false);
    assert.equal(await evaluate('document.querySelector("[data-archive-controls]").hidden'), true);
    const secondPage = await visible();
    assert.equal(secondPage[0], expected[12]);
    assert.equal(await evaluate('[...document.querySelectorAll("[data-blog-card]:not([hidden])")].every(card => getComputedStyle(card).display !== "none")'), true);
    assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true);
  }, { builtDirectory: 'dist' });
});
